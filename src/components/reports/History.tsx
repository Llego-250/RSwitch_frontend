// REQ-RPT-004 report history, from the API: every generated report this user
// may view under §14 — name, type, date, author and a download link. Runs
// still in the queue (§17.3) refresh on their own.
import { useState } from "react";
import { Download, FileText, Loader2, Search } from "lucide-react";
import { SectionCard } from "@/components/AppShell";
import { EmptyState, LoadState, selectCls, tdCls, thCls } from "@/components/compliance/ui";
import { errorMessage } from "@/lib/api";
import { fmtBytes, fmtDateTime } from "@/lib/governance";
import { downloadRun, useReportHistory, type ReportCatalog, type ReportRun } from "@/lib/reports";

function RunStatus({ run }: { run: ReportRun }) {
  if (run.status === "Completed")
    return <span className="text-[11px] font-semibold text-[#12825E]">Completed</span>;
  if (run.status === "Failed")
    return (
      <span className="text-[11px] font-semibold text-[#DC3154]" title={run.error}>
        Failed
      </span>
    );
  return (
    <span className="inline-flex items-center gap-1 text-[11px] font-semibold text-[#168FA8]">
      <Loader2 className="h-3 w-3 animate-spin" />
      {run.status}
    </span>
  );
}

export function History({ catalog }: { catalog: ReportCatalog }) {
  const [report, setReport] = useState("");
  const [mine, setMine] = useState(false);
  const [search, setSearch] = useState("");
  const [error, setError] = useState<string | null>(null);
  const history = useReportHistory({ report: report || undefined, mine });
  const viewable = catalog.types.filter((t) => t.can_view);
  const q = search.trim().toLowerCase();
  const rows = (history.data ?? []).filter(
    (r) =>
      !q ||
      r.name.toLowerCase().includes(q) ||
      r.generated_by.toLowerCase().includes(q) ||
      r.ref.toLowerCase().includes(q),
  );

  async function download(run: ReportRun) {
    setError(null);
    try {
      await downloadRun(run);
    } catch (e) {
      setError(errorMessage(e));
    }
  }

  return (
    <SectionCard
      noPad
      title="Report history"
      action={
        <div className="flex flex-wrap items-center gap-2">
          <div className="relative">
            <Search className="absolute left-2.5 top-1/2 -translate-y-1/2 h-3.5 w-3.5 text-[#7B8798]" />
            <input
              type="search"
              value={search}
              onChange={(e) => setSearch(e.target.value)}
              placeholder="Search name, author, RPT-…"
              className={`${selectCls} pl-8 w-56`}
            />
          </div>
          <select
            value={report}
            onChange={(e) => setReport(e.target.value)}
            className={selectCls}
            aria-label="Report type"
          >
            <option value="">All types I can view</option>
            {viewable.map((t) => (
              <option key={t.key} value={t.key}>
                {t.name}
              </option>
            ))}
          </select>
          <label className="inline-flex items-center gap-1.5 text-xs text-[#526174] dark:text-slate-300">
            <input type="checkbox" checked={mine} onChange={(e) => setMine(e.target.checked)} />
            Generated by me
          </label>
        </div>
      }
    >
      {error && <div className="px-5 py-2 text-xs font-medium text-[#DC3154]">{error}</div>}
      <LoadState loading={history.isLoading} error={history.error} />
      {history.data && rows.length === 0 && (
        <EmptyState icon={<FileText className="h-8 w-8" />} title="No reports yet">
          {history.data.length
            ? "No report matches the search."
            : "Reports you generate — and those of report types your role may view — appear here."}
        </EmptyState>
      )}
      {rows.length > 0 && (
        <div className="overflow-x-auto">
          <table className="w-full">
            <thead className="bg-slate-50 dark:bg-slate-800/60 border-b border-[#DCE3E8] dark:border-slate-800">
              <tr>
                {[
                  "Report",
                  "Type",
                  "Generated",
                  "Generated by",
                  "Filters",
                  "Format",
                  "Status",
                  "",
                ].map((h) => (
                  <th key={h} className={thCls}>
                    {h}
                  </th>
                ))}
              </tr>
            </thead>
            <tbody className="divide-y divide-slate-100 dark:divide-slate-800">
              {rows.map((r) => (
                <tr key={r.id} className="hover:bg-slate-50/70 dark:hover:bg-slate-800/40">
                  <td className={tdCls}>
                    <div className="font-semibold">{r.name}</div>
                    <div className="text-[10.5px] font-mono text-[#7B8798]">
                      {r.ref}
                      {r.schedule_id ? " · scheduled" : ""}
                    </div>
                  </td>
                  <td className={`${tdCls} whitespace-nowrap`}>{r.report_name}</td>
                  <td className={`${tdCls} whitespace-nowrap`}>{fmtDateTime(r.generated_at)}</td>
                  <td className={tdCls}>{r.generated_by}</td>
                  <td className={`${tdCls} text-[#526174] dark:text-slate-400 max-w-64`}>
                    {r.filters_text.length ? r.filters_text.join(" · ") : "None"}
                  </td>
                  <td className={`${tdCls} uppercase font-semibold`}>
                    {r.format}
                    {r.size_bytes ? (
                      <span className="block normal-case font-normal text-[10.5px] text-[#7B8798]">
                        {fmtBytes(r.size_bytes)}
                        {r.row_count !== null ? ` · ${r.row_count} rows` : ""}
                      </span>
                    ) : null}
                  </td>
                  <td className={tdCls}>
                    <RunStatus run={r} />
                  </td>
                  <td className={tdCls}>
                    {r.download_url && (
                      <button
                        onClick={() => download(r)}
                        className="inline-flex items-center gap-1 text-xs font-semibold text-[#168FA8] hover:underline cursor-pointer"
                      >
                        <Download className="h-3.5 w-3.5" />
                        Download
                      </button>
                    )}
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      )}
    </SectionCard>
  );
}
