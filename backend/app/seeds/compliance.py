def _incidents(session: Session, today: date, now: datetime) -> None:
    """Every §9.4 status, owners of different roles, and remediation
    actions — one overdue (escalates to senior Compliance)."""
    if session.exec(select(RemediationAction.id)).first():
        return
    officer, lead = _user(session, "compliance@rswitch.rw"), _user(session, "compliance.lead@rswitch.rw")
    admin, business = _user(session, "admin@rswitch.rw"), _user(session, "business@rswitch.rw")
    if not all((officer, lead, admin, business)):
        return
    by_code = {p.code: p for p in session.exec(select(Participant)).all()}

    def incident(code: str, description: str, severity: IssueSeverity, *, raised: datetime, owner: User,
                 raised_by: User = lead) -> Optional[Issue]:
        p = by_code.get(code)
        if p is None:
            return None
        row = session.exec(select(Issue).where(Issue.description == description)).first()
        if row is None:
            row = Issue(participant_id=p.id, description=description, severity=severity, created_at=raised)
        row.created_at = min(row.created_at, now - timedelta(days=1))
        row.incident_date = row.created_at.date() - timedelta(days=1)
        row.severity, row.raised_by_id, row.owner_id, row.assignee = severity, raised_by.id, owner.id, owner.full_name
        row.status = IssueStatus.open
        session.add(row)
        session.commit()
        session.refresh(row)
        return row

    def action(row: Issue, text: str, owner: User, due: date, completed: Optional[datetime] = None) -> None:
        session.add(RemediationAction(incident_id=row.id, description=text, owner_id=owner.id, due_date=due,
                                      status="Completed" if completed else "Open", completed_at=completed,
                                      completed_by=owner.full_name if completed else "", created_by=lead.full_name,
                                      created_at=row.acknowledged_at + timedelta(hours=3)))

    month = now.replace(day=1, hour=9, minute=0, second=0, microsecond=0)
    # Resolved: remediation complete, awaiting formal closure.
    kvu = incident("KVU", "Reconciliation mismatch on POS batch", IssueSeverity.medium, raised=month - timedelta(days=150), owner=officer)
    if kvu:
        kvu.acknowledged_at = kvu.created_at + timedelta(days=1)
        action(kvu, "Re-run the POS reconciliation for the affected batch with Kivu finance", admin,
               (kvu.created_at + timedelta(days=10)).date(), completed=kvu.created_at + timedelta(days=8))
        kvu.status, kvu.resolved_at = IssueStatus.resolved, kvu.created_at + timedelta(days=12)
        kvu.resolution_summary = "Kivu re-sent the POS batch with corrected settlement totals; reconciliation now matches exactly."
    # Open: raised, the owner hasn't acknowledged yet.
    incident("AKS", "Two of four expected batches missing this cycle", IssueSeverity.high, raised=now - timedelta(days=2), owner=officer)
    # Remediation In Progress, with one action overdue.
    mob = incident("MOB", "Duplicate transaction IDs in weekly file", IssueSeverity.critical, raised=now - timedelta(days=24), owner=admin)
    if mob:
        mob.acknowledged_at = mob.created_at + timedelta(hours=6)
        action(mob, "Re-submit the affected weekly files without duplicate IDs", officer, today - timedelta(days=12),
               completed=_at(today - timedelta(days=13), 15))
        action(mob, "Add a duplicate-ID check to MobiPesa's export job and confirm it in writing", admin, today - timedelta(days=3))
        mob.status = IssueStatus.remediation_in_progress
    # Under Investigation: acknowledged by its (senior) owner.
    nym = incident("NYM", "No submissions received in over a month", IssueSeverity.critical, raised=now - timedelta(days=5), owner=lead,
                   raised_by=officer)
    if nym:
        nym.acknowledged_at = nym.created_at + timedelta(hours=4)
        nym.status = IssueStatus.under_investigation
    # Closed.
    rus = incident("RUS", "Channel field left blank for most rows", IssueSeverity.low, raised=month - timedelta(days=100), owner=business)
    if rus:
        rus.acknowledged_at = rus.created_at + timedelta(days=1)
        action(rus, "Agree channel codes with Rubavu Union SACCO and update their export", business,
               (rus.created_at + timedelta(days=14)).date(), completed=rus.created_at + timedelta(days=11))
        rus.status, rus.resolved_at, rus.closed_at = IssueStatus.closed, rus.created_at + timedelta(days=12), rus.created_at + timedelta(days=15)
        rus.resolution_summary = "Rubavu now populates the channel field from its core banking export; three months verified clean."
    # Remediation In Progress, action not yet due.
    kvu2 = incident("KVU", "ATM settlement file delivered after the 10:00 cut-off two days running", IssueSeverity.high,
                    raised=now - timedelta(days=6), owner=officer)
    if kvu2:
        kvu2.acknowledged_at = kvu2.created_at + timedelta(hours=2)
        action(kvu2, "Agree a revised file-delivery schedule with Kivu operations", officer, today + timedelta(days=5))
        kvu2.status = IssueStatus.remediation_in_progress
    for row in (kvu, mob, nym, rus, kvu2):
        if row:
            session.add(row)
    # Incidents seeded before owners existed: link the owner where the name matches a user.
    session.commit()


