def _user(session: Session, email: str) -> Optional[User]:
    return session.exec(select(User).where(User.email == email)).first()


def _clip(when: datetime, now: datetime) -> datetime:
    return min(when, now - timedelta(minutes=30))


def _at(day: date, hour: int = 9) -> datetime:
    """A Kigali working hour on `day`, stored as naive UTC (UTC+2)."""
    return datetime.combine(day, time(hour - 2, 15))


def _template(session: Session, p: Participant, name: str, columns: list[tuple[str, str]], rule: dict | None = None) -> IngestionTemplate:
    existing = session.exec(select(IngestionTemplate).where(IngestionTemplate.participant_id == p.id, IngestionTemplate.name == name)).first()
    if existing:
        return existing
    template = IngestionTemplate(participant_id=p.id, name=name, version=1, applies_to=p.name,
                                 created_at=p.created_at)
    session.add(template)
    session.commit()
    session.refresh(template)
    for i, (col, kind) in enumerate(columns):
        session.add(TemplateColumn(template_id=template.id, name=col, type=kind, required=True, position=i,
                                   rule=(rule or {}).get(col, "")))
    session.commit()
    return template


def _pdf(title: str) -> bytes:
    from fpdf import FPDF

    pdf = FPDF()
    pdf.add_page()
    pdf.set_font("Helvetica", size=14)
    pdf.cell(0, 10, title.encode("latin-1", "replace").decode("latin-1"), new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("Helvetica", size=10)
    pdf.multi_cell(0, 6, "Demo document generated by app.seeds.compliance for RDIP development.")
    return bytes(pdf.output())


def _requirement(session: Session, p: Participant, name: str, reference: str, kind: str, frequency: str, due: date, *,
                 template_id: Optional[int] = None, doc_type_id: Optional[int] = None, description: str = "") -> ComplianceRequirement:
    req = ComplianceRequirement(participant_id=p.id, requirement_name=name, regulatory_reference=reference, kind=kind,
                                template_id=template_id, doc_type_id=doc_type_id, frequency=frequency, anchor_day=due.day,
                                due_date=due, description=description, created_by="Head of Compliance",
                                created_at=datetime.combine(p.registration_date or p.created_at.date(), time(8)))
    session.add(req)
    session.commit()
    session.refresh(req)
    return req


def _cycle(session: Session, req: ComplianceRequirement, due: date, opened: datetime) -> ComplianceCycle:
    cycle = ComplianceCycle(requirement_id=req.id, due_date=due, period=svc.period_label(due, req.frequency), opened_at=opened)
    session.add(cycle)
    session.flush()
    return cycle


def _link(session: Session, cycle: ComplianceCycle, obj) -> None:
    if isinstance(obj, Submission):
        session.add(ComplianceCycleItem(cycle_id=cycle.id, submission_id=obj.id, linked_at=obj.uploaded_at))
    else:
        session.add(ComplianceCycleItem(cycle_id=cycle.id, document_id=obj.id, linked_at=obj.uploaded_at))
    session.flush()


def _review(obj, status: str, when: datetime, *, reason: str = "", note: str = "", reviewer: str = REVIEWER) -> None:
    if isinstance(obj, Submission):
        obj.status = status
        obj.review_status = {"Under Review": "Pending Review", "Approved": "Approved", "Rejected": "Rejected"}[status]
    else:
        obj.review_status = status
    obj.reviewed_by = reviewer
    obj.reviewed_at = when
    obj.rejection_reason = reason
    obj.review_note = note


def _finish(session: Session, req: ComplianceRequirement) -> None:
    """Recompute every cycle oldest first; open the next cycle of a
    recurring requirement whose latest cycle is approved."""
    cycles = session.exec(select(ComplianceCycle).where(ComplianceCycle.requirement_id == req.id).order_by(ComplianceCycle.id)).all()
    for cycle in cycles:
        svc.recompute(session, cycle, requirement=req)
    if cycles:
        nxt = svc.roll_next(session, req, cycles[-1])
        if nxt is not None:
            nxt.opened_at = cycles[-1].approved_at or nxt.opened_at
    session.commit()


# ---- monthly returns built from the submissions already seeded ---------------

def _monthly_from_history(session: Session, req: ComplianceRequirement, subs: list[Submission], due_day: int, now: datetime) -> None:
    """One cycle per month a return was sent, due on `due_day` of that
    month. Corrections join the month of the attempt they correct; repeated
    attempts in a month are chained as corrections (§6.4)."""
    month_of: dict[int, tuple[int, int]] = {}
    groups: "OrderedDict[tuple[int, int], list[Submission]]" = OrderedDict()
    for s in sorted(subs, key=lambda s: (s.uploaded_at, s.id)):
        key = month_of.get(s.replaces_submission_id) if s.replaces_submission_id else None
        key = key or (s.uploaded_at.year, s.uploaded_at.month)
        month_of[s.id] = key
        groups.setdefault(key, []).append(s)
    for (year, month), items in sorted(groups.items()):
        due = date(year, month, min(due_day, 28))
        cycle = _cycle(session, req, due, datetime(year, month, 1))
        previous = None
        for s in items:
            s.requirement_id = req.id
            if previous is not None and s.replaces_submission_id is None and previous.result == SubmissionResult.failed:
                s.replaces_submission_id = previous.id
            if s.status == "Approved" and s.reviewed_at is None:
                s.reviewed_at = _clip(s.uploaded_at + timedelta(days=2), now)
                s.reviewed_by = s.reviewed_by or REVIEWER
            if s.status == "Under Review" and s.reviewed_at is None:
                s.reviewed_at = _clip(s.uploaded_at + timedelta(days=1), now)
                s.reviewed_by = REVIEWER
            session.add(s)
            session.flush()
            _link(session, cycle, s)
            previous = s
    session.commit()


def _current_month_story(session: Session, req: ComplianceRequirement, code: str, now: datetime) -> None:
    """Vary where each participant's current monthly return stands."""
    cycle = svc.current_cycle(session, req)
    if cycle is None:
        return
    items = [i.obj for i in svc.cycle_items(session, cycle)]
    if not items:
        return
    latest = items[-1]
    started = _clip(latest.uploaded_at + timedelta(days=1), now)
    if code == "KVU" and latest.status == "Submitted":
        _review(latest, "Under Review", started)
    elif code == "AKS" and latest.status == "Submitted":
        _review(latest, "Rejected", _clip(started + timedelta(hours=5), now),
                reason="Totals do not reconcile with the settlement report: 1,204 POS transactions are missing for the 3rd and 4th.")
    elif code == "RUS" and latest.status == "Submitted":
        _review(latest, "Approved", started, note="Totals reconciled with the settlement report.")
    elif code == "NYM" and latest.status == "Validation Failed":
        cycle.correction_requested_at = _clip(latest.uploaded_at + timedelta(days=1), now)
        cycle.correction_requested_by = REVIEWER
        cycle.correction_note = "Called Eric Niyonzima; Nyanza will re-export the file with numeric amounts."
        session.add(cycle)
    session.add(latest)
    session.commit()


# ---- quarterly prudential return (files generated here) ----------------------

def _prudential_csv(rng: random.Random, reporting: date, broken: bool) -> bytes:
    lines = ["indicator_code,indicator_name,value,reporting_date"]
    for code, name in INDICATORS:
        value = round(rng.uniform(5, 40) if code != "DEP" else rng.uniform(800, 90000), 2)
        lines.append(f"{code},{name},{value},{reporting.isoformat()}")
    if broken:  # a real failure: a missing value and a malformed date
        lines[2] = f"{INDICATORS[1][0]},{INDICATORS[1][1]},,{reporting.isoformat()}"
        lines[4] = f"{INDICATORS[3][0]},{INDICATORS[3][1]},1.2,31/13/{reporting.year}"
    return "\n".join(lines).encode()


def _record(session: Session, p: Participant, template: IngestionTemplate, req: ComplianceRequirement, data: bytes,
            uploaded_at: datetime, period: str, replaces: Optional[Submission] = None) -> Submission:
    """A return as the upload path records it (validated by the real
    engine, aggregates loaded) — sent outside any pipeline data source, like
    the inclusion returns."""
    columns = list(session.exec(select(TemplateColumn).where(TemplateColumn.template_id == template.id).order_by(TemplateColumn.position)).all())
    table = read_rows("return.csv", data)
    errors, warnings = validate_rows(table, columns)
    passed = not errors
    rows, totals, breakdowns = aggregate(table.rows, *identity_fields(columns)) if passed else (0, {}, {})
    slug = f"{p.code}_PRU_{uploaded_at:%Y%m%d%H%M}"
    key = f"submissions/{p.id}/demo-{slug}.csv"
    put_file(key, data, "text/csv")
    sub = Submission(participant_id=p.id, template_id=template.id, requirement_id=req.id, period=period,
                     filename=f"{slug}.csv", storage_key=key, uploaded_at=uploaded_at, uploaded_by=REVIEWER,
                     result=SubmissionResult.passed if passed else SubmissionResult.failed,
                     status="Submitted" if passed else "Validation Failed", records_received=len(table.rows),
                     error_count=len(errors), errors=errors, warning_count=len(warnings), warnings=warnings,
                     row_count=rows, numeric_totals=totals, breakdowns=breakdowns,
                     loaded_at=uploaded_at + timedelta(minutes=2) if passed else None,
                     replaces_submission_id=replaces.id if replaces else None)
    session.add(sub)
    session.commit()
    session.refresh(sub)
    return sub


def _quarter_label(due: date) -> str:
    end = (due.replace(day=1) - timedelta(days=1))  # returns cover the quarter before the deadline month
    return f"{end.year}-Q{(end.month - 1) // 3 + 1}"


def _prudential(session: Session, p: Participant, today: date, now: datetime, rng: random.Random) -> None:
    offset, story = PRUDENTIAL.get(p.code, (30, None))
    template = _template(session, p, "Quarterly prudential return", PRU_COLUMNS)
    due = today + timedelta(days=offset)
    previous_due = due - relativedelta(months=3)
    onboarded = p.registration_date or p.created_at.date()
    req = _requirement(session, p, "Quarterly prudential return", PRU_REF, svc.DATA_RETURN, "Quarterly",
                       previous_due if previous_due > onboarded else due, template_id=template.id,
                       description="Capital, liquidity and asset-quality indicators for the quarter just ended.")
    if previous_due > onboarded:
        cycle = _cycle(session, req, previous_due, datetime.combine(previous_due - relativedelta(months=3), time(8)))
        late = p.code == "AKS"
        sent = _at(previous_due + timedelta(days=2) if late else previous_due - timedelta(days=5), 10)
        sub = _record(session, p, template, req, _prudential_csv(rng, previous_due, False), sent, _quarter_label(previous_due))
        _review(sub, "Approved", sent + timedelta(days=2), note="Ratios within prudential limits.")
        session.add(sub)
        _link(session, cycle, sub)
        session.commit()
        svc.recompute(session, cycle, requirement=req)
        session.commit()
    cycle = _cycle(session, req, due, now - timedelta(days=60))
    period = _quarter_label(due)
    if story == "corrected":
        bad = _record(session, p, template, req, _prudential_csv(rng, due, True), _at(today - timedelta(days=3), 11), period)
        good = _record(session, p, template, req, _prudential_csv(rng, due, False), _at(today - timedelta(days=1), 14), period, replaces=bad)
        _link(session, cycle, bad)
        _link(session, cycle, good)
    elif story == "rejected":
        sub = _record(session, p, template, req, _prudential_csv(rng, due, False), _at(today - timedelta(days=4), 10), period)
        _review(sub, "Rejected", _at(today - timedelta(days=2), 15),
                reason="Liquidity coverage ratio is reported at 12%; Akagera's own board pack shows 112%. Please re-check the LCR line.")
        session.add(sub)
        _link(session, cycle, sub)
    elif story == "failed":
        sub = _record(session, p, template, req, _prudential_csv(rng, due, True), _at(today - timedelta(days=1), 10), period)
        _link(session, cycle, sub)
    elif story == "in_review":
        sub = _record(session, p, template, req, _prudential_csv(rng, due, False), _at(today - timedelta(days=2), 9), period)
        _review(sub, "Under Review", _at(today - timedelta(days=1), 10))
        session.add(sub)
        _link(session, cycle, sub)
    session.commit()
    _finish(session, req)


# ---- documents ---------------------------------------------------------------

def _doc(session: Session, p: Participant, doc_type: RequiredDocumentType, req: ComplianceRequirement, uploaded: datetime,
         expiry: Optional[date], status: str, label: str) -> ComplianceDocument:
    key = f"documents/{p.id}/demo-{doc_type.name.replace(' ', '_')}-{uploaded:%Y%m%d}.pdf"
    put_file(key, _pdf(f"{p.name} - {doc_type.name} ({label})"), "application/pdf")
    doc = ComplianceDocument(participant_id=p.id, doc_type_id=doc_type.id, filename=f"{p.code}_{doc_type.name.replace(' ', '_')}_{label}.pdf",
                             storage_key=key, uploaded_at=uploaded, expiry_date=expiry, uploaded_by=REVIEWER,
                             requirement_id=req.id, review_status=status)
    session.add(doc)
    session.commit()
    session.refresh(doc)
    return doc


def _adopt_on_file(session: Session, p: Participant, doc_type: RequiredDocumentType, req: ComplianceRequirement,
                   due: date) -> Optional[ComplianceDocument]:
    """The document the core seed put on file becomes the approved delivery
    of the previous cycle (received before it was due)."""
    doc = session.exec(select(ComplianceDocument).where(ComplianceDocument.participant_id == p.id,
                                                        ComplianceDocument.doc_type_id == doc_type.id)).first()
    if doc is None:
        return None
    received = _at(due - timedelta(days=12), 10)
    doc.uploaded_at, doc.uploaded_by, doc.requirement_id = received, REVIEWER, req.id
    _review(doc, "Approved", received + timedelta(days=1), note="Original checked against the BNR register.")
    session.add(doc)
    session.commit()
    return doc


def _annual_document(session: Session, p: Participant, doc_type: RequiredDocumentType, name: str, reference: str,
                     today: date, now: datetime, story: dict) -> None:
    """Renewal is due when the document on file expires; with none on
    file, at story['due'] days from today."""
    on_file = session.exec(select(ComplianceDocument).where(ComplianceDocument.participant_id == p.id,
                                                            ComplianceDocument.doc_type_id == doc_type.id)).first()
    due = on_file.expiry_date if on_file and on_file.expiry_date else today + timedelta(days=story.get("due", 60))
    previous_due = due - relativedelta(years=1)
    req = _requirement(session, p, name, reference, svc.DOCUMENT, "Annual", previous_due if on_file else due, doc_type_id=doc_type.id)
    if on_file:
        cycle = _cycle(session, req, previous_due, datetime.combine(previous_due - relativedelta(years=1), time(8)))
        _link(session, cycle, _adopt_on_file(session, p, doc_type, req, previous_due))
        session.commit()
        svc.recompute(session, cycle, requirement=req)
        session.commit()
    cycle = _cycle(session, req, due, datetime.combine(previous_due, time(8)) if on_file else now - timedelta(days=30))
    kind = story.get("kind")
    if kind == "submitted":
        _link(session, cycle, _doc(session, p, doc_type, req, _at(today - timedelta(days=1), 15), due + relativedelta(years=1), "Submitted", "renewal"))
    elif kind == "in_review":
        doc = _doc(session, p, doc_type, req, _at(today - timedelta(days=2), 11), due + relativedelta(years=1), "Submitted", "renewal")
        _review(doc, "Under Review", _at(today - timedelta(days=1), 9))
        session.add(doc)
        _link(session, cycle, doc)
    elif kind == "correction":
        doc = _doc(session, p, doc_type, req, _at(today - timedelta(days=6), 10), None, "Submitted", "2025")
        _review(doc, "Rejected", _at(today - timedelta(days=4), 16),
                reason="The certificate sent is last year's audit and expired in June; we need the current certification.")
        session.add(doc)
        _link(session, cycle, doc)
        cycle.correction_requested_at = _at(today - timedelta(days=3), 10)
        cycle.correction_requested_by = REVIEWER
        cycle.correction_note = "Emailed Jean Bosco Habimana for the current certificate."
        session.add(cycle)
    session.commit()
    _finish(session, req)


def _uat(session: Session, p: Participant, doc_type: RequiredDocumentType, today: date, now: datetime, due_in: int) -> None:
    on_file = session.exec(select(ComplianceDocument).where(ComplianceDocument.participant_id == p.id,
                                                            ComplianceDocument.doc_type_id == doc_type.id)).first()
    onboarded = p.registration_date or p.created_at.date()
    due = onboarded + timedelta(days=20) if on_file else today + timedelta(days=due_in)
    req = _requirement(session, p, "UAT sign-off", UAT_REF, svc.DOCUMENT, "Ad hoc", due, doc_type_id=doc_type.id,
                       description="Signed user-acceptance test report before go-live on the switch.")
    cycle = _cycle(session, req, due, datetime.combine(onboarded, time(8)) if on_file else now - timedelta(days=10))
    if on_file:
        _link(session, cycle, _adopt_on_file(session, p, doc_type, req, due))
    session.commit()
    _finish(session, req)


