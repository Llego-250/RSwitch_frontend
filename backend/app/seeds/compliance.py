def seed(session: Session) -> None:
    officer = _user(session, "compliance@rswitch.rw")
    if officer is None:
        return
    now = datetime.utcnow()
    today = svc.today_for(session)
    if session.exec(select(ComplianceRequirement.id)).first() is None:
        # The inclusion returns are linked to the register too; make sure they exist.
        from app.seeds import inclusion

        inclusion.seed(session)
        _register(session, today, now)
    _incidents(session, today, now)
    refresh_statuses(session, today)


def _register(session: Session, today: date, now: datetime) -> None:
    rng = random.Random(1007)
    doc_types = {t.name: t for t in session.exec(select(RequiredDocumentType)).all()}
    licence, infosec, uat = doc_types.get("Operating licence"), doc_types.get("Infosec certification"), doc_types.get("UAT sign-off")
    licence_story = {"NYM": {"due": 7}, "HCS": {"due": 75}, "MFS": {"due": 110}, "NDS": {"due": 140}}
    infosec_story = {"KVU": {"kind": "submitted"}, "RUS": {"kind": "in_review"}, "AKS": {"due": 9, "kind": "correction"},
                     "NYM": {"due": -5}, "HCS": {"due": 30}, "MFS": {"due": 50}, "NDS": {"due": 14}}
    uat_due = {"NYM": 14, "RUS": 30}

    for p in session.exec(select(Participant).order_by(Participant.id)).all():
        source = session.exec(select(Integration).where(Integration.participant_id == p.id,
                                                        Integration.integration_mode == IntegrationMode.manual.value)
                              .order_by(Integration.id)).first()
        # Monthly transaction return, from the returns already received.
        if source and source.template_id:
            subs = session.exec(select(Submission).where(Submission.participant_id == p.id, Submission.template_id == source.template_id,
                                                         Submission.integration_id == source.id)).all()
            first_due = min((s.uploaded_at for s in subs), default=now).date().replace(day=10)
            req = _requirement(session, p, "Monthly transaction return", TX_REF, svc.DATA_RETURN, "Monthly", first_due,
                               template_id=source.template_id,
                               description="Every switched transaction of the month, validated against the expected schema.")
            _monthly_from_history(session, req, list(subs), 10, now)
            if not subs:
                _cycle(session, req, first_due if first_due > today else today + timedelta(days=10), now)
            _current_month_story(session, req, p.code, now)
            _finish(session, req)

        # Monthly financial inclusion return (the returns the inclusion seed loaded).
        fin = session.exec(select(Submission).where(Submission.participant_id == p.id, Submission.filename.like(f"{p.code}_FIN_%"))).all()
        if fin:
            template = _template(session, p, "Financial inclusion return", FIN_COLUMNS,
                                 rule={"region": "regex:Kigali City|Northern Province|Southern Province|Eastern Province|Western Province"})
            for s in fin:
                s.template_id = s.template_id or template.id
                session.add(s)
            session.commit()
            first_due = min(s.uploaded_at for s in fin).date().replace(day=15)
            req = _requirement(session, p, "Monthly financial inclusion return", FIN_REF, svc.DATA_RETURN, "Monthly", first_due,
                               template_id=template.id, description="Accounts, active users and transactions by region for the previous month.")
            _monthly_from_history(session, req, list(fin), 15, now)
            _finish(session, req)

        _prudential(session, p, today, now, rng)
        if licence:
            _annual_document(session, p, licence, "Operating licence renewal", LICENCE_REF, today, now, licence_story.get(p.code, {}))
        if infosec:
            _annual_document(session, p, infosec, "Information security certification", INFOSEC_REF, today, now,
                             infosec_story.get(p.code, {}))
        if uat:
            _uat(session, p, uat, today, now, uat_due.get(p.code, 21))
