import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const tokensPath = path.join(__dirname, 'src', 'tokens.json');
const distDir = path.join(__dirname, 'dist');

if (!fs.existsSync(distDir)) {
  fs.mkdirSync(distDir, { recursive: true });
}

const tokensData = JSON.parse(fs.readFileSync(tokensPath, 'utf8'));

// Generate TypeScript definitions for Web
const tsContent = `// Auto-generated by Style Dictionary compilation script
export const RDIPTokens = ${JSON.stringify(tokensData, null, 2)} as const;
export type RDIPTokenType = typeof RDIPTokens;
`;

fs.writeFileSync(path.join(distDir, 'tokens.ts'), tsContent, 'utf8');

// Generate JSON tokens for Mobile (React Native)
fs.writeFileSync(path.join(distDir, 'tokens.json'), JSON.stringify(tokensData, null, 2), 'utf8');

console.log('✅ Design Tokens successfully compiled to dist/tokens.ts (Web) and dist/tokens.json (Mobile)');
